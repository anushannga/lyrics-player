"""Build pixel-exact ISI bitmaps. Requires Pillow; no font installation needed."""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/isidisap_0.ttf'
SCALE = 4
SIZE = 28
font = ImageFont.truetype(str(FONT), SIZE * SCALE)

def ink(text):
    box = font.getbbox(text, stroke_width=1)
    im = Image.new('L', (box[2]-box[0]+8, box[3]-box[1]+8))
    ImageDraw.Draw(im).text((4-box[0], 4-box[1]), text, font=font, fill=255, stroke_width=1)
    bounds = im.getbbox()
    return im.crop(bounds)

def fits(text):
    return ink(text).width <= 124*SCALE

def wrap(text):
    if fits(text):
        return [text]
    words = text.split()
    choices = []
    for split in range(1,len(words)):
        rows = [' '.join(words[:split]), ' '.join(words[split:])]
        if all(fits(row) for row in rows):
            choices.append((abs(ink(rows[0]).width-ink(rows[1]).width), rows))
    if not choices:
        raise ValueError('Line needs more than two rows; split the lyric cue: '+text)
    return min(choices, key=lambda v:v[0])[1]

def bitmap(rows):
    strips=[]
    for row in rows:
        im=ink(row)
        # Resample only from 4x rasterization to native pixels. Never squeeze text.
        im=im.resize(((im.width+SCALE-1)//SCALE, (im.height+SCALE-1)//SCALE),Image.Resampling.LANCZOS)
        im=im.point(lambda p:255 if p>=170 else 0).convert('1')
        strips.append(im)
    height=sum(i.height for i in strips)+2*(len(strips)-1)
    if height>64:
        raise ValueError(f'Ink height {height} would clip vowel marks')
    canvas=Image.new('1',(128,64))
    y=(64-height)//2
    for strip in strips:
        canvas.paste(strip,((128-strip.width)//2,y))
        y+=strip.height+2
    return canvas

lines=(ROOT/'lyrics_isi.txt').read_text().splitlines()
frames=[]; unique=[]; indices=[]; report=[]
for line in lines:
    rows=wrap(line)
    frame=bitmap(rows)
    packed=bytes(sum((int(bool(frame.getpixel((x+b,y))))<<b) for b in range(8)) for y in range(64) for x in range(0,128,8))
    if packed not in unique:
        unique.append(packed)
    indices.append(unique.index(packed));frames.append(frame)
    report.append({'isi':line,'rows':rows,'bitmap':indices[-1]})
    frame.resize((768,384),Image.Resampling.NEAREST).save(ROOT/'previews'/f'line-{len(frames):02d}.png')

checksum=hashlib.sha256(b''.join(unique)+bytes(indices)).hexdigest()[:12]
header=['// Generated by tools/render_lyrics.py; 1 bit/pixel, native 128x64, LSB first.',
        '#pragma once','#include <Arduino.h>',f'#define LYRICS_COUNT {len(lines)}',
        f'#define LYRICS_BITMAP_COUNT {len(unique)}',f'#define LYRICS_ID "{checksum}"',
        'const uint8_t lyric_index[LYRICS_COUNT] PROGMEM = {'+','.join(map(str,indices))+'};',
        'const uint8_t lyrics_bits[LYRICS_BITMAP_COUNT][1024] PROGMEM = {']
for data in unique:
    header.append('{')
    header.extend('  '+','.join(f'0x{v:02x}' for v in data[i:i+16])+',' for i in range(0,1024,16))
    header.append('},')
header.append('};')
(ROOT/'LyricsKaraokeClear'/'lyrics_bits.h').write_text('\n'.join(header)+'\n')
(ROOT/'render_report.json').write_text(json.dumps({'font':str(FONT),'size':SIZE,'id':checksum,'lines':report},ensure_ascii=False,indent=2))
# Exact pixels, enlarged with nearest-neighbor for inspection.
sheet=Image.new('RGB',(128*4*3, (64*4+28)*((len(frames)+2)//3)),'#15251f')
d=ImageDraw.Draw(sheet)
for i,frame in enumerate(frames):
    x=(i%3)*512; y=(i//3)*284
    d.text((x+8,y+4),f'{i+1:02d}',fill='#ddf2bf')
    colored=Image.new('RGB',(128,64),'#b5ce83')
    colored.paste('#172814',mask=frame)
    sheet.paste(colored.resize((512,256),Image.Resampling.NEAREST),(x,y+28))
sheet.save(ROOT/'previews'/'all-lyrics.png')
print(f'{len(lines)} lyric cues / {len(unique)} unique bitmaps / {len(unique)*1024} flash bytes; ID {checksum}')
